#include <iostream>
using namespace std;
int main(){
    float x,y;

    cout << "Masukan Angka Pertama: " ;
    cin >> x;
    cout << "Masukan Angka Kedua: ";
    cin >> y;    

    cout << "Hasil Penambahan: " << x + y << endl;
    cout << "Hasil Pengurangan: " << x - y << endl;
    cout << "Hasil Perkalian: " << x * y << endl;
    cout << "Hasil Pembagian: " << x / y << endl;
}